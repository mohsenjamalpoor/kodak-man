const lerp = (a, b, f) => a + (b - a) * f;

// تقریب تابع خطا (Abramowitz-Stegun)
function erf(x) {
  const s = Math.sign(x);
  const ax = Math.abs(x);
  const t = 1 / (1 + 0.3275911 * ax);
  const poly =
    ((((1.061405429 * t - 1.453152027) * t + 1.421413741) * t - 0.284496736) *
      t +
      0.254829592) *
    t;
  return s * (1 - poly * Math.exp(-ax * ax));
}
const cdf = (z) => 0.5 * (1 + erf(z / Math.SQRT2));

export function lengthForAge(sex, months, cm) {
  const rows = TABLE[sex];
  const m = Math.min(Math.max(months, 0), MAX_MONTHS);
  const i = Math.floor(m);
  const f = m - i;
  const a = rows[i];
  const b = rows[Math.min(i + 1, rows.length - 1)];
  const p15 = lerp(a[0], b[0], f);
  const median = lerp(a[1], b[1], f);
  const p85 = lerp(a[2], b[2], f);
  // در این استاندارد توزیع قد متقارن است: انحراف معیار ≈ فاصله صدک ۱۵ و ۸۵ تقسیم بر ۲٫۰۷۲
  const sd = (p85 - p15) / (2 * 1.0364);
  const z = (cm - median) / sd;
  return { median, sd, z, percentile: cdf(z) * 100 };
}
