// امتیاز Z متناظر با صدک‌های ۳، ۱۵، ۵۰، ۸۵ و ۹۷
const Z5 = [-1.8808, -1.0364, 0, 1.0364, 1.8808];
const Z3 = [-1.0364, 0, 1.0364];

// تقریب تابع خطا (Abramowitz-Stegun) برای تبدیل Z به صدک
function erf(x) {
  const s = Math.sign(x);
  const ax = Math.abs(x);
  const t = 1 / (1 + 0.3275911 * ax);
  const poly =
    ((((1.061405429 * t - 1.453152027) * t + 1.421413741) * t - 0.284496736) *
      t +
      0.254829592) *
    t;
  return s * (1 - poly * Math.exp(-ax * ax));
}
const cdf = (z) => 0.5 * (1 + erf(z / Math.SQRT2));

// درون‌یابی ردیف جدول بین ماه‌ها (سن اعشاری)
function rowAt(rows, months) {
  const m = Math.min(Math.max(months, 0), rows.length - 1);
  const i = Math.floor(m);
  const f = m - i;
  const a = rows[i];
  const b = rows[Math.min(i + 1, rows.length - 1)];
  return a.map((v, k) => v + (b[k] - v) * f);
}

// Z از روی مقدارهای صدکی (خطی بین نقطه‌ها، با برون‌یابی در دو سر)
function zFromRow(vals, zs, x) {
  const n = vals.length;
  let k = 0;
  while (k < n - 2 && x > vals[k + 1]) k++;
  const x0 = vals[k];
  const x1 = vals[k + 1];
  const z0 = zs[k];
  const z1 = zs[k + 1];
  return z0 + ((x - x0) / (x1 - x0)) * (z1 - z0);
}

function evaluate(rows, zs, months, x) {
  const row = rowAt(rows, months);
  const z = zFromRow(row, zs, x);
  const median = row[(row.length - 1) / 2];
  return { z, percentile: cdf(z) * 100, median };
}

export const evaluateHeight = (sex, months, cm) =>
  evaluate(LENGTH[sex], Z3, months, cm);
export const evaluateWeight = (sex, months, kg) =>
  evaluate(WEIGHT[sex], Z5, months, kg);
